import { afterEach, describe, expect, it } from 'vitest';
import { mkdtemp, mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { WordActivityService, localDay } from '../lib/wordActivity';

const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });

describe('saved writing activity', () => {
  it.each(['unstaged', 'staged'])('recognizes a saved exact restoration before and after committing (%s)', async (staging) => {
    const root = await mkdtemp(path.join(tmpdir(), 'weather-restore-'));
    roots.push(root);
    let date = '2026-11-01T12:00:00-08:00';
    const git = (...args: string[]) => execFileSync('git', args, { cwd: root, encoding: 'utf8', env: { ...process.env, GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date } });
    await mkdir(path.join(root, 'vault'));
    git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.com');
    const name = 'vault/A restored note é.md';
    const note = path.join(root, name);
    const original = '---\ntitle: Original\ntype: note\n---\nthree original words\n';
    await writeFile(note, original);
    git('add', '.'); git('commit', '-qm', 'initial');
    date = '2026-11-02T12:00:00-08:00';
    await rm(note);
    git('add', '-A'); git('commit', '-qm', 'delete');
    const service = new WordActivityService(path.join(root, 'vault'));
    const now = new Date(2026, 10, 3, 12);
    expect((await service.load(now)).totals.touched).toBe(6);
    await writeFile(note, original);
    if (staging === 'staged') git('add', name);
    const saved = await service.load(now);
    expect(saved.totals).toEqual({ added: 3, edited: 0, removed: 0, touched: 3 });
    expect(saved.weeks.flatMap(week => week.days).find(day => day.date === '2026-11-02')?.touched).toBe(0);
    // Canceling the saved restoration must not leave the cached deletion suppressed.
    await rm(note);
    expect((await service.load(now)).totals.touched).toBe(6);
    await writeFile(note, original);
    date = '2026-11-03T12:00:00-08:00';
    git('add', '-A'); git('commit', '-qm', 'restore');
    expect((await service.load(now)).totals).toEqual(saved.totals);
    await writeFile(note, original.replace('original words', 'better words'));
    expect((await service.load(now)).totals).toEqual({ added: 3, edited: 1, removed: 0, touched: 4 });
  });
  it.each(['unstaged', 'destination staged', 'deletion staged', 'staged'])('counts only body edits across a note rename (%s)', async (staging) => {
    const root = await mkdtemp(path.join(tmpdir(), 'weather-rename-'));
    roots.push(root);
    const git = (...args: string[]) => execFileSync('git', args, { cwd: root, encoding: 'utf8', env: { ...process.env, GIT_AUTHOR_DATE: '2026-11-17T12:00:00-08:00', GIT_COMMITTER_DATE: '2026-11-17T12:00:00-08:00' } });
    await mkdir(path.join(root, 'vault'));
    git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.com');
    const oldPath = 'vault/An earlier title.md';
    const newPath = 'vault/A different title é.md';
    const body = 'clear words here\n'.repeat(40);
    const original = `---\ntitle: Earlier title\nslug: stable-url\ntype: note\n---\n${body}`;
    await writeFile(path.join(root, oldPath), original);
    git('add', '.'); git('commit', '-m', 'initial');
    const service = new WordActivityService(path.join(root, 'vault'));
    const now = new Date(2026, 10, 17, 12);
    const baseline = (await service.load(now)).totals;
    await rename(path.join(root, oldPath), path.join(root, newPath));
    await writeFile(path.join(root, newPath), original.replace('Earlier title', 'Different title'));
    if (staging === 'destination staged') git('add', newPath);
    if (staging === 'deletion staged') git('add', '-u');
    if (staging === 'staged') git('add', '-A');
    const index = await readFile(path.join(root, '.git/index'));
    const objects = await readdir(path.join(root, '.git/objects'), { recursive: true });
    const head = git('rev-parse', 'HEAD');
    expect((await service.load(now)).totals).toEqual(baseline);
    const revised = original.replace('Earlier title', 'Different title').replace('clear', 'better');
    await writeFile(path.join(root, newPath), revised);
    const saved = await service.load(now);
    expect(saved.totals).toEqual({ ...baseline, edited: 1, touched: baseline.touched + 1 });
    expect(await readFile(path.join(root, '.git/index'))).toEqual(index);
    expect(await readdir(path.join(root, '.git/objects'), { recursive: true })).toEqual(objects);
    expect(git('rev-parse', 'HEAD')).toBe(head);
    expect(await readFile(path.join(root, newPath), 'utf8')).toBe(revised);
    git('add', '-A'); git('commit', '-m', 'rename and revise');
    expect((await service.load(now)).totals).toEqual(saved.totals);
    // A copy is new writing when the source still exists; a real deletion still counts.
    await writeFile(path.join(root, 'vault/copy.md'), revised);
    expect((await service.load(now)).totals.added).toBe(saved.totals.added + 120);
    await rm(path.join(root, 'vault/copy.md'));
    await rm(path.join(root, newPath));
    expect((await service.load(now)).totals.removed).toBe(120);
  });
  it('includes staged, unstaged and new prose once, excludes private files, and remains stable after committing', async () => {
    const root = await mkdtemp(path.join(tmpdir(), 'weather-words-'));
    roots.push(root);
    const git = (...args: string[]) => execFileSync('git', args, { cwd: root, encoding: 'utf8', env: { ...process.env, GIT_AUTHOR_DATE: '2026-10-30T12:00:00-04:00', GIT_COMMITTER_DATE: '2026-10-30T12:00:00-04:00' } });
    await mkdir(path.join(root, 'vault/scratch'), { recursive: true });
    git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.com');
    const metadata = '---\ntitle: Note title\ntype: note\nexclude_modified_update: false\n---\n';
    await writeFile(path.join(root, 'vault/note.md'), metadata + 'old words here\n');
    git('add', '.'); git('commit', '-m', 'initial');
    const service = new WordActivityService(path.join(root, 'vault'));
    const now = new Date(2026, 9, 30, 12);
    expect((await service.load(now)).totals.touched).toBe(3);
    await writeFile(path.join(root, 'vault/note.md'), metadata.replace('Note title', 'Updated title') + 'old words here\n');
    expect((await service.load(now)).totals.touched).toBe(3);
    git('add', '.'); git('commit', '-m', 'Metadata changes should not count as writing');
    expect((await service.load(now)).totals.touched).toBe(3);
    await writeFile(path.join(root, 'vault/note.md'), metadata + 'clear words here\n');
    git('add', 'vault/note.md');
    await writeFile(path.join(root, 'vault/note.md'), metadata + 'clear words here today\n');
    await writeFile(path.join(root, 'vault/new.md'), metadata + 'another thought\n');
    await writeFile(path.join(root, 'vault/scratch/private.md'), 'private words never counted\n');
    const saved = await service.load(now);
    expect(saved.totals).toEqual({ added: 6, edited: 1, removed: 0, touched: 7 });
    expect((await service.load(now)).totals).toEqual(saved.totals);
    git('add', '.'); git('commit', '-m', 'revised');
    expect((await service.load(now)).totals).toEqual(saved.totals);
    await writeFile(path.join(root, 'vault/note.md'), metadata + 'clear words\n');
    expect((await service.load(now)).totals.removed).toBe(2);
  });
  it('uses the local calendar day', () => {
    expect(localDay(new Date(2026, 9, 30, 23, 59))).toBe('2026-10-30');
    expect(localDay(new Date(2026, 9, 31, 0, 1))).toBe('2026-10-31');
  });
});
